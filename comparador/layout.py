from .i18n import tr
'Workspace layout: configuration above, results in the center, actions always visible.'
from PySide6.QtCore import Qt
from PySide6.QtWidgets import *
from .appearance import icon
from . import __version__
from .settings import RESULT_COLUMNS, DEFAULT_COLUMN_WIDTHS

def build_window(w):
    from .ui import label, button, PreviewCard
    shell = QWidget()
    shell.setObjectName('shell')
    w.setCentralWidget(shell)
    main = QVBoxLayout(shell)
    main.setContentsMargins(16, 10, 16, 10)
    main.setSpacing(6)
    top = QHBoxLayout()
    top.addWidget(label(tr('Compare files'), 'brand'))
    top.addWidget(label(__version__, 'muted'))
    top.addStretch()
    w.setup_toggle = button(tr('Hide scan options'))
    w.incidents_button = button(tr('Issues'))
    w.incidents_button.setEnabled(False)
    w.incidents_button.clicked.connect(w.show_incidents)
    w.export_button = button(tr('Export report'))
    w.export_button.setIcon(icon('export'))
    w.export_button.clicked.connect(w.export_report)
    top.addWidget(w.setup_toggle)
    w.scan_details_button = button(tr('Scan details'))
    w.scan_details_button.setEnabled(False)
    top.addWidget(w.scan_details_button)
    top.addWidget(w.incidents_button)
    top.addWidget(w.export_button)
    main.addLayout(top)
    w.root_summary = label('', 'muted')
    w.root_summary.setMinimumWidth(0)
    w.root_summary.setSizePolicy(QSizePolicy.Policy.Ignored, QSizePolicy.Policy.Preferred)
    w.root_summary.hide()
    setup = QFrame()
    w.setup_panel = setup
    setup.setObjectName('setup')
    config = QVBoxLayout(setup)
    config.setContentsMargins(14, 10, 14, 12)
    mode_row = QHBoxLayout()
    w.folder_mode = QComboBox()
    w.folder_mode.addItems([tr('One folder'), tr('Primary and secondary')])
    mode_row.addWidget(label(tr('Compare')))
    mode_row.addWidget(w.folder_mode)
    mode_row.addSpacing(16)
    w.recursive = QCheckBox(tr('Include subfolders'))
    w.recursive.setChecked(True)
    mode_row.addWidget(w.recursive)
    w.file_filter = QComboBox()
    w.file_filter.addItems([tr('All files'), tr('Videos only')])
    mode_row.addWidget(w.file_filter)
    mode_row.addStretch()
    w.unlock = QCheckBox(tr('Allow removing primary files'))
    w.unlock.setToolTip(tr('This only affects the primary folder. Secondary files can be managed after scanning.'))
    w.unlock.clicked.connect(w.unlock_primary)
    w.unlock.toggled.connect(w.update_actions)
    mode_row.addWidget(w.unlock)
    config.addLayout(mode_row)
    paths = QHBoxLayout()
    first = QVBoxLayout()
    w.primary_label = label(tr('Primary folder for reference copies'), 'section')
    first.addWidget(w.primary_label)
    w.primary_path, row = w._folder_row(tr('Choose folder...'))
    first.addLayout(row)
    paths.addLayout(first, 1)
    w.secondary_box = QWidget()
    second = QVBoxLayout(w.secondary_box)
    second.setContentsMargins(10, 0, 0, 0)
    second.addWidget(label(tr('Secondary folder to organize'), 'section'))
    w.secondary_path, row = w._folder_row(tr('Choose secondary folder...'))
    second.addLayout(row)
    paths.addWidget(w.secondary_box, 1)
    w.secondary_box.hide()
    config.addLayout(paths)
    analysis = QHBoxLayout()
    w.analysis_mode = QComboBox()
    w.analysis_mode.addItems([tr('Exact copies only'), tr('Exact copies and similar videos')])
    analysis.addWidget(w.analysis_mode)
    w.video_profile = QComboBox()
    w.video_profile.addItems([tr('Quick scan with up to 24 samples'), tr('Full scan of the entire video')])
    w.video_profile.setToolTip(tr('Quick scan uses direct seeking and may miss edits or trims. Full scan examines more frames.'))
    analysis.addWidget(w.video_profile)
    w.threshold_box = QWidget()
    thresholds = QHBoxLayout(w.threshold_box)
    thresholds.setContentsMargins(0, 0, 0, 0)
    thresholds.addWidget(label(tr('Similarity')))
    w.similarity = QSpinBox()
    w.similarity.setRange(70, 99)
    w.similarity.setValue(90)
    w.similarity.setSuffix(' %')
    thresholds.addWidget(w.similarity)
    thresholds.addWidget(label(tr('Coverage')))
    w.coverage = QSpinBox()
    w.coverage.setRange(50, 100)
    w.coverage.setValue(80)
    w.coverage.setSuffix(' %')
    thresholds.addWidget(w.coverage)
    w.recalculate = button(tr('Apply'))
    w.recalculate.setToolTip(tr('Recalculate matches from existing fingerprints without decoding again.'))
    w.recalculate.clicked.connect(w.recalculate_matches)
    thresholds.addWidget(w.recalculate)
    analysis.addWidget(w.threshold_box)
    analysis.addStretch()
    w.scan_button = button(tr('Scan'), name='primary')
    w.scan_button.setIcon(icon('scan', '#ffffff'))
    w.scan_button.clicked.connect(w.start_scan)
    analysis.addWidget(w.scan_button)
    w.cancel_button = button(tr('Cancel'))
    w.cancel_button.clicked.connect(w.cancel_current)
    analysis.addWidget(w.cancel_button)
    config.addLayout(analysis)
    main.addWidget(setup)
    w.threshold_box.hide()
    w.video_profile.hide()
    w.folder_mode.currentIndexChanged.connect(lambda i: w.secondary_box.setVisible(i == 1))
    w.folder_mode.currentIndexChanged.connect(lambda i: w.primary_label.setText(tr('Primary folder for reference copies') if i else tr('Folder to review')))
    w.analysis_mode.currentIndexChanged.connect(lambda i: w.threshold_box.setVisible(i == 1))
    w.analysis_mode.currentIndexChanged.connect(lambda i: w.video_profile.setVisible(i == 1))

    def toggle():
        setup.setVisible(not setup.isVisible())
        w.setup_toggle.setText(tr('Hide scan options') if setup.isVisible() else tr('Edit folders and scan options'))
    w.setup_toggle.clicked.connect(toggle)
    w.notice = label(tr('Choose your folders and start a scan. Then review and manage the copies.'), 'notice', True)
    main.addWidget(w.notice)
    w.scan_details_button.clicked.connect(lambda: w.notice.setVisible(w.notice.isHidden()))
    counts = QHBoxLayout()
    counts.addWidget(w.root_summary, 1)
    w.metrics = []
    w.metric_labels = []
    for suffix in (tr('files'), tr('exact groups'), tr('similar pairs'), tr('secondary files without an exact copy')):
        metric = label('N/A', 'section')
        w.metrics.append(metric)
        counts.addWidget(metric)
        caption = label(suffix, 'muted')
        w.metric_labels.append(caption)
        counts.addWidget(caption)
        counts.addSpacing(10)
    main.addLayout(counts)
    filters = QHBoxLayout()
    w.scope_label = label(tr('Show files from'))
    filters.addWidget(w.scope_label)
    w.scope_filter = QComboBox()
    w.scope_filter.currentIndexChanged.connect(w.populate)
    filters.addWidget(w.scope_filter)
    w.view_filter = QComboBox()
    w.view_filter.currentIndexChanged.connect(w.populate)
    filters.addWidget(w.view_filter)
    w.search = QLineEdit()
    w.search.setPlaceholderText(tr('Search name or path'))
    w.search.setClearButtonEnabled(True)
    w.search.textChanged.connect(w.populate)
    filters.addWidget(w.search, 1)
    main.addLayout(filters)
    selection = QHBoxLayout()
    w.select_copies_button = button(tr('Select extra copies'))
    w.select_copies_button.setIcon(icon('select'))
    w.select_copies_button.setToolTip(tr('Select visible extra copies while keeping references. Primary copies are preferred when comparing two folders.'))
    w.select_copies_button.clicked.connect(w.select_redundant)
    selection.addWidget(w.select_copies_button)
    w.select_all_button = button(tr('Select all visible files'))
    w.select_all_button.clicked.connect(w.select_all_visible)
    selection.addWidget(w.select_all_button)
    w.clear_button = button(tr('Clear selection'))
    w.clear_button.clicked.connect(w.clear_selection)
    selection.addWidget(w.clear_button)
    w.comparison_toggle = button(tr('Show comparison'))
    w.comparison_toggle.setEnabled(False)
    w.comparison_toggle.clicked.connect(w.toggle_comparison)
    selection.addWidget(w.comparison_toggle)
    selection.addStretch()
    w.selected_label = label(tr('0 selected'), 'section')
    selection.addWidget(w.selected_label)
    main.addLayout(selection)
    side = w.preferences.comparison_position == 'right'
    split = QSplitter(Qt.Orientation.Horizontal if side else Qt.Orientation.Vertical)
    split.setChildrenCollapsible(False)
    split.setHandleWidth(8)
    w.results_split = split
    w.table = QTableWidget(0, 9)
    w.table.setHorizontalHeaderLabels([tr(title) for _, title in RESULT_COLUMNS])
    w.table.setAlternatingRowColors(True)
    w.table.setShowGrid(False)
    w.table.setSelectionBehavior(QAbstractItemView.SelectionBehavior.SelectRows)
    w.table.setSelectionMode(QAbstractItemView.SelectionMode.ExtendedSelection)
    w.table.setEditTriggers(QAbstractItemView.EditTrigger.NoEditTriggers)
    w.table.verticalHeader().hide()
    w.table.verticalHeader().setDefaultSectionSize(34)
    w.table.setMinimumWidth(460)
    w.table.setSortingEnabled(True)
    header = w.table.horizontalHeader()
    header.setSectionResizeMode(QHeaderView.ResizeMode.Interactive)
    header.setMinimumSectionSize(48)
    header.setMaximumSectionSize(2400)
    header.setToolTip(tr('Drag a column border to resize it. Double-click the border to fit its contents. Widths are saved automatically.'))
    for col, (key, _) in enumerate(RESULT_COLUMNS):
        w.table.setColumnWidth(col, w.preferences.column_widths.get(key, DEFAULT_COLUMN_WIDTHS[key]))
    header.sectionClicked.connect(lambda col: w.toggle_all_visible() if col == 0 else None)
    w.table.itemSelectionChanged.connect(w.show_details)
    w.table.itemChanged.connect(w.update_actions)
    split.addWidget(w.table)
    w.preview_panel = QWidget()
    details = QVBoxLayout(w.preview_panel)
    details.setContentsMargins(0, 3, 0, 0)
    w.peer_combo = QComboBox()
    w.peer_combo.setSizeAdjustPolicy(QComboBox.SizeAdjustPolicy.AdjustToMinimumContentsLengthWithIcon)
    w.peer_combo.setMinimumContentsLength(12)
    w.peer_combo.addItem(tr('Select a row to compare copies'))
    w.peer_combo.currentIndexChanged.connect(w.show_peer)
    peer_row = QHBoxLayout()
    peer_row.addWidget(w.peer_combo, 1)
    details.addLayout(peer_row)
    cards = QVBoxLayout() if side else QHBoxLayout()
    cards.setSpacing(6)
    w.left_preview = PreviewCard(tr('FILE UNDER REVIEW'))
    w.right_preview = PreviewCard(tr('REFERENCE COPY'))
    w.left_preview.set_compact(side)
    w.right_preview.set_compact(side)
    cards.addWidget(w.left_preview, 0 if side else 1)
    cards.addWidget(w.right_preview, 0 if side else 1)
    details.addLayout(cards)
    w.evidence = label('', 'muted', True)
    details.addWidget(w.evidence)
    if side:
        details.addStretch(1)
    w.preview_scroll = QScrollArea()
    w.preview_scroll.setWidgetResizable(True)
    w.preview_scroll.setMinimumWidth(400 if side else 0)
    w.preview_scroll.setWidget(w.preview_panel)
    split.addWidget(w.preview_scroll)
    w.preview_scroll.hide()
    split.setStretchFactor(0, 1)
    split.setStretchFactor(1, 0)
    main.addWidget(split, 1)
    w.selection_hint = label(tr('Check files to move or remove them. Highlighting a row only opens the comparison.'), 'muted', True)
    main.addWidget(w.selection_hint)
    actions = QHBoxLayout()
    w.transfer_button = button(tr('Move to primary'))
    w.transfer_button.setIcon(icon('move'))
    w.transfer_button.clicked.connect(w.transfer_selected)
    actions.addWidget(w.transfer_button)
    w.move_button = button(tr('Move to another folder...'))
    w.move_button.setIcon(icon('folder'))
    w.move_button.clicked.connect(w.move_selected)
    actions.addWidget(w.move_button)
    actions.addStretch()
    w.trash_button = button(tr('Send selected files to Recycle Bin...'), name='danger')
    w.trash_button.setIcon(icon('trash', '#9a2936'))
    w.trash_button.clicked.connect(w.trash_selected)
    actions.addWidget(w.trash_button)
    main.addLayout(actions)
    bottom = QHBoxLayout()
    w.progress_label = label(tr('Ready to scan'), 'muted')
    w.progress_label.setMinimumWidth(0)
    bottom.addWidget(w.progress_label, 1)
    w.progress = QProgressBar()
    w.progress.setFixedWidth(180)
    w.progress.setRange(0, 100)
    w.progress.setValue(0)
    w.progress.setTextVisible(False)
    bottom.addWidget(w.progress)
    main.addLayout(bottom)
    w.config_widgets = [w.folder_mode, w.primary_path, w.secondary_path, w.recursive, w.file_filter, w.analysis_mode, w.video_profile, w.similarity, w.coverage, w.unlock]
    w.folder_mode.currentIndexChanged.connect(w.configure_result_filters)
    w.configure_result_filters()
